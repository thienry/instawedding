import process from 'node:process'

import { DeleteObjectsCommand, S3Client } from '@aws-sdk/client-s3'

import { createServiceClient } from './supabase.js'

const MAX_KEYS_PER_REQUEST = 1000

/** R2 client, or `null` when the storage is not configured. */
export function createR2(): { client: S3Client; bucket: string } | null {
  const accountId = process.env.R2_ACCOUNT_ID
  const accessKeyId = process.env.R2_ACCESS_KEY_ID
  const secretAccessKey = process.env.R2_SECRET_ACCESS_KEY
  if (!accountId || !accessKeyId || !secretAccessKey) return null
  return {
    client: new S3Client({
      region: 'auto',
      endpoint: `https://${accountId}.r2.cloudflarestorage.com`,
      credentials: { accessKeyId, secretAccessKey },
    }),
    bucket: process.env.R2_BUCKET_NAME || 'instawedding',
  }
}

/** Object of a post. Only matches names generated by the upload endpoint. */
export function getMediaKey(mediaUrl: string): string | null {
  return (
    /^\/media\/(uploads\/\d{4}\/\d{2}\/[0-9a-f-]{36}\.[a-z0-9]{3,4})$/.exec(mediaUrl)?.[1] ?? null
  )
}

/**
 * Deletes the media of posts already deleted. Media still used by another post
 * stays: otherwise, a guest could delete the photo of someone else by posting
 * its address. Never throws, since the posts are gone anyway.
 */
export async function deleteMedia(mediaUrls: readonly string[]): Promise<void> {
  try {
    const storage = createR2()
    if (!storage) return
    const keys: string[] = []
    for (const url of new Set(mediaUrls)) {
      const key = getMediaKey(url)
      if (!key) continue
      const { data, error } = await createServiceClient()
        .from('posts')
        .select('id')
        .eq('media_url', url)
        .limit(1)
      if (error) throw error
      if (data.length === 0) keys.push(key)
    }
    for (let i = 0; i < keys.length; i += MAX_KEYS_PER_REQUEST) {
      const Objects = keys.slice(i, i + MAX_KEYS_PER_REQUEST).map((Key) => ({ Key }))
      const { Errors } = await storage.client.send(
        new DeleteObjectsCommand({ Bucket: storage.bucket, Delete: { Objects, Quiet: true } })
      )
      if (Errors?.length) console.error('[media]', Errors)
    }
  } catch (error) {
    console.error('[media]', error)
  }
}
