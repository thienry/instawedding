import { S3Client } from '@aws-sdk/client-s3'
import { beforeEach, expect, it, vi } from 'vitest'

import { POST as deletePost } from '../delete-post.js'
import { deleteMedia, getMediaKey } from './media.js'

const ID = '11111111-1111-1111-1111-111111111111'
const OTHER = '22222222-2222-2222-2222-222222222222'
const key = (n: number) => `uploads/2026/12/${n}1111111-1111-1111-1111-111111111111.webp`
const url = (n: number) => `/media/${key(n)}`

interface Row {
  id: string
  media_url: string
  client_session_id: string
}
const db = vi.hoisted(() => ({ posts: [] as Row[] }))

vi.mock('./supabase.js', () => ({
  getBearerUser: async (req: Request) => {
    const id = req.headers.get('authorization')
    return id ? { id } : null
  },
  createServiceClient: () => ({
    from: () => {
      const filters: [keyof Row, string][] = []
      let isDelete = false
      const builder = {
        select: () => builder,
        limit: () => builder,
        delete: () => {
          isDelete = true
          return builder
        },
        eq: (column: keyof Row, value: string) => {
          filters.push([column, value])
          return builder
        },
        then: (resolve: (result: unknown) => void) => {
          const data = db.posts.filter((row) => filters.every(([c, v]) => row[c] === v))
          if (isDelete) db.posts = db.posts.filter((row) => !data.includes(row))
          resolve({ data, error: null })
        },
      }
      return builder
    },
  }),
}))

let deleted: string[] = []
const send = (user: string | null, postId: unknown = ID) =>
  deletePost(
    new Request('https://x.test', {
      method: 'POST',
      headers: user ? { authorization: user } : {},
      body: JSON.stringify({ postId }),
    })
  )

beforeEach(() => {
  deleted = []
  db.posts = [{ id: ID, media_url: url(1), client_session_id: 'ana' }]
  for (const name of ['R2_ACCOUNT_ID', 'R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY']) {
    vi.stubEnv(name, 'x')
  }
  vi.spyOn(console, 'error').mockImplementation(() => {})
  vi.spyOn(S3Client.prototype, 'send').mockImplementation(async (command: unknown) => {
    const { input } = command as { input: { Delete: { Objects: { Key: string }[] } } }
    deleted.push(...input.Delete.Objects.map(({ Key }) => Key))
    return {}
  })
})

it('deletes the post of the guest and its media', async () => {
  expect((await send('ana')).status).toBe(200)
  expect(db.posts).toEqual([])
  expect(deleted).toEqual([key(1)])
})

it('refuses the posts of others', async () => {
  expect((await send(null)).status).toBe(401)
  expect((await send('bob')).status).toBe(403)
  expect((await send('ana', 'x')).status).toBe(400)
  expect(db.posts).toHaveLength(1)
  expect(deleted).toEqual([])
})

it('accepts a post that is already gone', async () => {
  db.posts = []
  expect((await send('ana')).status).toBe(200)
})

it('keeps media used by another post', async () => {
  db.posts.push({ id: OTHER, media_url: url(1), client_session_id: 'bob' })
  await send('bob', OTHER)
  await send('ana')
  expect(deleted).toEqual([key(1)])
  deleted = []
  db.posts = [{ id: OTHER, media_url: url(2), client_session_id: 'bob' }]
  await deleteMedia([url(2), url(3)])
  expect(deleted).toEqual([key(3)])
})

it('only touches names generated by the app', () => {
  expect(getMediaKey(url(1))).toBe(key(1))
  for (const bad of [
    '/media/uploads/../x',
    'https://x.test/a.webp',
    `${url(1)}?a`,
    '/media/a.webp',
  ]) {
    expect(getMediaKey(bad)).toBeNull()
  }
})

it('survives a storage failure', async () => {
  vi.spyOn(S3Client.prototype, 'send').mockRejectedValue(new Error('down') as never)
  expect((await send('ana')).status).toBe(200)
})
