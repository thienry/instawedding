-- InstaWedding Supabase Database Schema & Seed
-- Execute this script in the Supabase SQL Editor (https://supabase.com/dashboard)

-- 1. Challenges Table
CREATE TABLE IF NOT EXISTS public.challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  icon TEXT NOT NULL DEFAULT '✨',
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. Posts Table
CREATE TABLE IF NOT EXISTS public.posts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  author_name TEXT NOT NULL,
  author_avatar_url TEXT,
  media_url TEXT NOT NULL,
  caption TEXT,
  challenge_id BIGINT REFERENCES public.challenges(id) ON DELETE SET NULL,
  client_session_id TEXT NOT NULL DEFAULT 'anonymous',
  likes_count INTEGER NOT NULL DEFAULT 0 CHECK (likes_count >= 0),
  is_approved BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.posts ADD COLUMN IF NOT EXISTS author_avatar_url TEXT;

CREATE INDEX IF NOT EXISTS idx_posts_created_at ON public.posts (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_posts_is_approved ON public.posts (is_approved);

-- 3. Likes Table
CREATE TABLE IF NOT EXISTS public.likes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  post_id UUID NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  client_session_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_likes_post_session UNIQUE (post_id, client_session_id)
);

CREATE INDEX IF NOT EXISTS idx_likes_post_session ON public.likes (post_id, client_session_id);

-- 4. Atomic Like Counter RPCs
CREATE OR REPLACE FUNCTION public.increment_likes(target_post_id UUID)
RETURNS public.posts
LANGUAGE sql
SECURITY DEFINER
AS $$
  UPDATE public.posts
  SET likes_count = likes_count + 1
  WHERE id = target_post_id
  RETURNING *;
$$;

CREATE OR REPLACE FUNCTION public.decrement_likes(target_post_id UUID)
RETURNS public.posts
LANGUAGE sql
SECURITY DEFINER
AS $$
  UPDATE public.posts
  SET likes_count = GREATEST(0, likes_count - 1)
  WHERE id = target_post_id
  RETURNING *;
$$;

